// ---- Helper: build a tool def -----------------------------------------------
function ITEMDATA_mkTool(tier, kind, damage, stack) {
  return {
    tier: ITEMDATA_TIER_IDX[tier],
    kind,
    speed: ITEMDATA_SPD[tier],
    damage,
    durability: ITEMDATA_DUR[tier],
    stack: stack || 1,
  };
}

// ---- Helper: build an armor def --------------------------------------------
function ITEMDATA_mkArmor(mat, slot) {
  return {
    slot,
    defense: ITEMDATA_ARMOR_DEF[mat][slot],
    durability: ITEMDATA_ARMOR_DUR[mat][slot],
    tier: ITEMDATA_ARMOR_TIER[mat],
  };
}

