// ===========================================================================
// itemsFromBlocks — generate placeable block items for all self-dropping blocks
// ===========================================================================
export function itemsFromBlocks(registry) {
  const generated = [];
  const existingIds = new Set(ITEM_DEFS.map((d) => d.id));
  for (const def of registry.byId) {
    if (!def) continue;
    // Skip air, system blocks, and blocks that don't drop themselves
    if (def.group === 'system') continue;
    const dropsSelf = (def.drops && def.drops.some((d) => d.item === def.name))
      || (def.drops === undefined);
    const silkSelf = def.silkTouchDrop === def.name;
    if (!dropsSelf && !silkSelf) continue;
    if (existingIds.has(def.name)) continue;
    generated.push({
      id: def.name,
      name: def.display || def.name,
      icon: 'block',
      stack: 64,
      group: def.group || 'blocks',
      fuelTicks: def.fuelTicks || 0,
      block: def.name,
    });
    existingIds.add(def.name);
  }
  return generated;
}

// ===========================================================================
// ITEMS_BY_ID — built lazily (caller must call initItemsMap after merging)
// We build from ITEM_DEFS only here; itemsFromBlocks result gets merged outside.
// ===========================================================================
export const ITEMS_BY_ID = new Map(ITEM_DEFS.map((d) => [d.id, d]));

export function getItem(id) {
  const d = ITEMS_BY_ID.get(id);
  if (!d) throw new Error(`Unknown item id: '${id}'`);
  return d;
}

export function isTool(id) {
  const d = ITEMS_BY_ID.get(id);
  return !!(d && d.tool);
}

export function toolTierOf(id) {
  const d = ITEMS_BY_ID.get(id);
  if (!d || !d.tool) return 0;
  return d.tool.tier || 0;
}
